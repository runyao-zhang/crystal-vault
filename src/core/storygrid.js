// 3.0 刀 32：故事线/结构窗的**格点**（用户 09-28）。
//
// 用户的原话：「整个结构窗和故事线采用世界坐标，但是只有世界坐标可不行……
// 每次移动是移动一个单位……建议是和卡片等比例吧这个最小单位」。
//
// ---- 单位是怎么算出来的 ----
//
// 拿**卡片的宽**当基准（用户说「和卡片等比例」）：
//
//     最小单位 UNIT = 卡片宽 ÷ 10 = 210 ÷ 10 = 21px
//     左右一步 = 2 × UNIT = 42px      （用户说的 0.2）
//     上下一步 = 1 × UNIT = 21px      （用户说的 0.1）
//
// 为什么左右是两格、上下是一格：用户给的例子就是 0.2 / 0.1，同一个基准下的
// 两倍关系。翻译成"卡片"就是**左右 5 步正好一张卡宽**（210 ÷ 42），
// 上下约 4.5 步一张卡高（96 ÷ 21）——横向密一点、纵向疏一点，和卡片本身
// 210×96 ≈ 2.19:1 的横宽比例基本对得上。取整数是为了好算，
// 差的那 9% 不值得把 21 换成 21.875。
//
// ⚠️ **吸附量子是最小单位（21×21），不是方向键那一步**。方向键按一下动
// 2 格或 1 格，但拖拽吸附落在 21 的方格上——吸附要的是"摆得准"，
// 方向键要的是"按一下就挪一段"，两件事的粒度本来就不该一样。
//
// ---- 坐标以哪儿为准 ----
//
// **左下角**（用户第 3 条）。所以纵向吸附要连**高度**一起算：
// 先把下边缘对到格点上，再倒推出上边缘。对卡片来说高度是固定的 96，
// 这一条退化成"整体差一个常数"；对收纳方框来说高度是你拉的，差别是真的。
//
// ⚠️ **存量位置一律不动。** 格点只在新的一次拖动/微调时生效，不会把用户
// 已经摆好的东西集体挪一格——那是不可逆的破坏，而且他根本没按任何键。
// 代价是：一张从没被碰过的老卡片可能停在格点外，动它一下就归位了。

import { NODE_W } from "./storylayout.js";

/** 最小单位 = 卡片宽的 1/10。卡片的尺寸是可配置的，所以这里跟着算，不写死 21。 */
export const UNIT = Math.max(4, Math.round(NODE_W / 10));

/** 方向键一步：左右 / 上下。**单位是像素**——调用方按像素用，不必再乘。 */
export const STEP_X = UNIT * 2;
export const STEP_Y = UNIT;

// 3.0 刀 34：`snapX` / `snapY` 现在只给下面 `snapPos` 用，`onGrid` 整个删了
// （收纳方框不走格点之后就没有调用方了）。**不 export 了**——它们是这个模块的
// 内部零件，而"对外只暴露一个 `snapPos`"能少一处"有人只吸了一半"的机会
// （只按 x 吸、忘了 y 要带高度，出来的东西会差一个卡片高）。

/** 把横坐标对到格点上（左下角的 x 就是左边缘的 x）。 */
function snapX(x) {
  const v = Number(x);
  if (!Number.isFinite(v)) return 0;
  return Math.round(v / UNIT) * UNIT;
}

/**
 * 把**上边缘**的 y 对到格点上，判据是**下边缘**（用户第 3 条）。
 *
 * @param {number} y 上边缘此刻在哪（`crystalPos` / 手动框存的都是这个）
 * @param {number} [h] 这个东西有多高。不给就按 0 算（等于直接对 y）。
 */
function snapY(y, h) {
  const v = Number(y);
  if (!Number.isFinite(v)) return 0;
  const hh = Number.isFinite(Number(h)) ? Number(h) : 0;
  // 先量下边缘 → 对格 → 再倒推回上边缘。写成 `snap(v + hh) - hh` 一行也等价，
  // 拆开是为了让"对的是下面那条边"这件事在代码里看得见。
  const bottom = v + hh;
  return Math.round(bottom / UNIT) * UNIT - hh;
}

/** 一次把 x / y 都对好（y 要带高度）。 */
export function snapPos(x, y, h) {
  return { x: snapX(x), y: snapY(y, h) };
}
